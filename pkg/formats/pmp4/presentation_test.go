func FuzzPresentationUnmarshal(f *testing.F) {
	for _, ca := range casesPresentation {
		f.Add(ca.enc)
	}

	f.Fuzz(func(t *testing.T, b []byte) {
		var p Presentation
		err := p.Unmarshal(bytes.NewReader(b))
		if err != nil {
			return
		}

		require.NotEmpty(t, p.Tracks)

		for _, track := range p.Tracks {
			require.NotZero(t, track.TimeScale)

			for _, sample := range track.Samples {
				require.NotZero(t, sample.PayloadSize)

				var pl []byte
				pl, err = sample.GetPayload()
				if err != nil {
					return
				}

				require.Equal(t, sample.PayloadSize, uint32(len(pl)))
			}
		}

		var buf bytes.Buffer
		err = p.Marshal(&buf)
		require.NoError(t, err)
	})
}
