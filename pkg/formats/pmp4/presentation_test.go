type seekFailer struct {
	io.ReadSeeker
	fail bool
}

func (r *seekFailer) Seek(offset int64, whence int) (int64, error) {
	if r.fail {
		return 0, fmt.Errorf("seek error")
	}
	return r.ReadSeeker.Seek(offset, whence)
}

